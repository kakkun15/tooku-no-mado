  // 前の曲は「次の曲」の左右反転
  PIX.prev = PIX.next.map(r => r.split('').reverse().join(''));

  const cache = {};
  function svg(name) {
    if (cache[name]) return cache[name];
    const rows = PIX[name]; if (!rows) return '';
    const w = rows[0].length, h = rows.length; let full = '', soft = '';
    rows.forEach((r, y) => {
      // 横に続く点は1つの長方形にまとめる
      for (let x = 0; x < w;) {
        const c = r[x]; if (c === '.') { x++; continue; }
        let e = x; while (e < w && r[e] === c) e++;
        const rect = `<rect x="${x}" y="${y}" width="${e - x}" height="1"/>`;
        if (c === '+') soft += rect; else full += rect;
        x = e;
      }
    });
    return (cache[name] = `<svg class="px" viewBox="0 0 ${w} ${h}" aria-hidden="true" focusable="false" shape-rendering="crispEdges" fill="currentColor">${full}${soft ? `<g opacity=".5">${soft}</g>` : ''}</svg>`);
  }
  // data-icon="名前" の要素の先頭にアイコンを入れる
  function fill(root) { (root || document).querySelectorAll('[data-icon]').forEach(el => { if (!el.querySelector('svg.px')) el.insertAdjacentHTML('afterbegin', svg(el.dataset.icon)); }); }
  window.TookuIcons = { svg, fill, names: Object.keys(PIX) };
